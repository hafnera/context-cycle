def fmt_tokens(tokens):
    return f"~{tokens/1000:.1f}k tok" if tokens >= 1000 else f"~{tokens} tok"


def current_model_and_window():
    """Best-effort: the current model from user settings, and its context window.

    Models with the "[1m]" suffix run with a 1M-token window; everything else
    is assumed to use the standard 200k window.
    """
    model = None
    try:
        settings = json.loads((Path.home() / ".claude" / "settings.json").read_text())
        model = settings.get("model")
    except (OSError, json.JSONDecodeError):
        pass
    window = 1_000_000 if model and "[1m]" in model else 200_000
    return model or "unknown, assuming 200k window", window



def import_summary(chars):
    est_tokens = chars // 4
    model, window = current_model_and_window()
    pct = est_tokens / window * 100
    pct_str = "<0.1" if 0 < pct < 0.1 else f"{pct:.1f}"
    return (f"Imported context: ~{est_tokens/1000:.1f}k tokens ≈ {pct_str}% of the "
            f"{window//1000}k-token context window (model: {model})")


def parse_any(agent, path, all_text=True):
    if agent == "codex":
        return parse_codex_session(path, all_text=all_text)
    if agent == "remote":
        if isinstance(path, CloudRef):
            return parse_cloud_session(path.id, all_text=all_text)
        for rec, blob in remote_sessions():
            if blob == path:
                return parse_remote_session(rec, blob, all_text=all_text)
        raise SystemExit(f"error: remote session cache not readable: {path}")
    parsed = parse_claude_session(path, all_text=all_text)
    if agent == "desktop":
        meta = desktop_meta_for(path) or {}
        parsed["agent"] = "desktop"
        if meta.get("title"):
            parsed["title"] = meta["title"]
        parsed["cwd"] = meta.get("originCwd") or meta.get("cwd") or parsed["cwd"]
        parsed["desktop_session_id"] = meta.get("sessionId")
        parsed["model"] = meta.get("model")
    return parsed


def cmd_list(args):
    entries = discover(args.agent, args.project, args.all_projects)
    codex_titles = codex_index_titles() if args.agent in ("codex", "all") else {}
    now = datetime.now(timezone.utc)
    rows = []
    for agent, path in entries:
        if len(rows) >= args.limit:
            break
        if isinstance(path, CloudRef):
            s = path.meta; ctx = (s.get("external_metadata") or {}).get("context_usage") or {}
            if args.grep and args.grep.lower() not in (s.get("title") or "").lower():
                continue
            rows.append({"agent": "remote", "session_id": path.id,
                         "project": cloud_project_label(s), "title": s.get("title"),
                         "user_messages": None, "start": fmt_ts(parse_ts(s.get("created_at"))),
                         "end": fmt_ts(parse_ts(s.get("updated_at"))), "condensed_chars": None,
                         "est_tokens": None, "cloud_context_tokens": ctx.get("used_tokens"),
                         "status": s.get("status"), "active": False, "path": str(path)})
            continue
        parsed = parse_any(agent, path)
        if parsed["user_messages"] == 0 and not args.include_empty:
            continue
        if args.grep:
            needle = args.grep.lower()
            haystack = " ".join(t["text"] for t in parsed["turns"]) + " " + (parsed["title"] or "")
            if needle not in haystack.lower():
                continue
        if agent == "codex" and parsed["session_id"] in codex_titles:
            parsed["title"] = codex_titles[parsed["session_id"]]
        mtime = datetime.fromtimestamp(ref_mtime(path), tz=timezone.utc)
        active = (now - mtime).total_seconds() < ACTIVE_WINDOW_SECONDS
        condensed_chars = len(render_markdown(parsed))
        rows.append({
            "agent": agent,
            "session_id": parsed["session_id"],
            "project": parsed["cwd"],
            "title": parsed["title"],
            "user_messages": parsed["user_messages"],
            "start": fmt_ts(parsed["first_ts"]),
            "end": fmt_ts(parsed["last_ts"]),
            "condensed_chars": condensed_chars,
            "est_tokens": condensed_chars // 4,
            "active": active,
            "path": str(path),
        })
    rows.sort(key=lambda r: r["end"] if r["end"] != "?" else "", reverse=True)
    if args.json:
        print(json.dumps(rows, indent=2, ensure_ascii=False))
        return
    if not rows:
        print("No sessions found. Try --all-projects, --agent all or --include-empty.")
        return
    # Group by project entity, projects ordered by their most recent activity.
    groups = {}
    for r in rows:
        groups.setdefault(r["project"] or "(unknown project)", []).append(r)
    for project, group in groups.items():
        print(f"📁 {project} — {len(group)} session(s)")
        for r in group:
            flag = "  *ACTIVE* (probably the running session)" if r["active"] else ""
            sid = r["session_id"][:8] if r["session_id"] else "?"
            if r.get("est_tokens") is None:  # cloud session: metadata only
                ctx = r.get("cloud_context_tokens")
                extra = f"{r.get('status') or ''}, session ctx ~{int(ctx)/1000:.0f}k" if ctx else (r.get("status") or "")
                print(f"   [{r['agent']}] {sid}  {r['end']}  {'  ? msgs':>8}  {'(cloud)':>10}  "
                      f"{snippet(r['title'] or '', 60)}  [{extra}]")
                continue
            print(f"   [{r['agent']}] {sid}  {r['end']}  {r['user_messages']:>3} msgs  "
                  f"{fmt_tokens(r['est_tokens']):>10}  {snippet(r['title'] or '', 70)}{flag}")


def truncate(text, max_chars):
    if max_chars and len(text) > max_chars:
        omitted = len(text) - max_chars
        return text[:max_chars].rstrip() + f"\n\n*[… truncated, {omitted:,} more chars]*"
    return text


def render_markdown(parsed, max_chars=0):
    lines = []
    agent_name = {"claude": "Claude Code", "codex": "Codex CLI",
                  "desktop": "Claude Desktop (local coding session)",
                  "remote": "claude.ai/code remote session"}.get(parsed["agent"], parsed["agent"])
    lines.append("# Imported session context")
    lines.append(f"- **Agent:** {agent_name}")
    lines.append(f"- **Project:** {parsed['cwd'] or '?'}")
    lines.append(f"- **Session:** `{parsed['session_id']}` — {parsed['title']}")
    lines.append(f"- **Time:** {fmt_ts(parsed['first_ts'])} → {fmt_ts(parsed['last_ts'])}")
    lines.append(f"- **User messages:** {parsed['user_messages']}")
    lines.append("")
    lines.append("> Condensed transcript: user messages, the main agent's progress notes and "
                 "final answer per turn, and subagent results (summary + full report). Tool "
                 "calls, tool results and thinking are omitted.")
    if parsed.get("source"):
        lines.append(f"> Source: {parsed['source']}.")
    if parsed.get("head_cut"):
        lines.append("> ⚠ Desktop caches long remote sessions tail-only (head cut): the "
                     "earliest part of this session is not available locally.")
    if parsed.get("omitted_users"):
        lines.append(f"> ⚠ The first {parsed['omitted_users']} user messages were "
                     "omitted (--last); rerun without --last for the full history.")
    lines.append("")
    for turn in parsed["turns"]:
        if turn["role"] == "command":
            lines.append(f"*⌘ User ran:* `{turn['text']}`")
            lines.append("")
            continue
        if turn["role"] == "event":
            lines.append(f"*⚙ {turn['text']}*")
            lines.append("")
            continue
        if turn["role"] == "assistant_progress":
            lines.append(truncate(turn["text"], max_chars))  # main agent's note between tool calls
            lines.append("")
            continue
        if turn["role"] == "subagent":
            lines.append("---")
            lines.append(f"### 🧭 Subagent «{turn['name']}» — result as received by the main agent")
            lines.append("")
            lines.append(truncate(turn["summary"], max_chars) if turn["summary"] else "*(background agent finished; see full report below)*")
            if turn.get("report"):
                lines.append("")
                lines.append(f"**Here is the full report from subagent «{turn['name']}»:**")
                lines.append("")
                lines.append(truncate(turn["report"], max_chars))
            lines.append("")
            continue
        lines.append("---")
        if turn["role"] == "user":
            when = f" — {fmt_ts(turn['ts'])}" if turn["ts"] else ""
            lines.append(f"### 👤 User{when}")
        elif turn["role"] == "summary":
            lines.append("### 📋 Carried-over summary of an earlier conversation")
        else:
            lines.append("### 🤖 Assistant (final answer)")
        lines.append("")
        lines.append(truncate(turn["text"], max_chars))
        lines.append("")
    return "\n".join(lines)


def cmd_extract(args):
    targets = []
    if args.current:
        # The currently running session: the most recently written session file
        # of this project. Inside Claude Code that is a claude session.
        agent = "claude" if args.agent == "all" else args.agent
        entries = discover(agent, args.project, False)
        if not entries:
            print("error: no current session found for this project", file=sys.stderr)
            sys.exit(1)
        targets = [entries[0]]
    elif args.path:
        agent = args.agent if args.agent != "all" else None
        if agent is None:
            # Guess by location/content
            agent = "codex" if ".codex" in str(args.path) else "claude"
        targets = [(agent, Path(args.path))]
    else:
        if not args.session_ids:
            print("error: give a session id prefix, or --path FILE", file=sys.stderr)
            sys.exit(2)
        entries = discover(args.agent, args.project, args.all_projects)
        for sid in args.session_ids:
            if sid.startswith("session_"):
                sid = "cse_" + sid[len("session_"):]   # claude.ai URL id -> cache id
            if sid.startswith("cse_") and args.agent not in ("remote", "all"):
                args.agent = "remote"
            if sid.startswith("cse_"):
                entries = [e for e in discover("remote", args.project, True)]
            match = None
            for agent, path in entries:
                stem = path.stem
                real_id = stem
                if agent == "codex":
                    meta = codex_read_meta(path)
                    real_id = (meta or {}).get("id") or stem
                elif agent == "desktop":
                    real_id = (desktop_meta_for(path) or {}).get("sessionId") or stem
                elif agent == "remote":
                    real_id = path.id if isinstance(path, CloudRef) else next(
                        (remote_session_id(r) for r, b in remote_sessions() if b == path), stem)
                if stem.startswith(sid) or real_id.startswith(sid) or sid in stem or sid in real_id:
                    match = (agent, path)
                    break
            if not match and sid.startswith("cse_"):
                if cloud_token() and cloud_sessions():
                    # not in the list (e.g. very old) — try the id directly
                    if cloud_get(f"{CLOUD_API}/{sid}/events", {"limit": 1}):
                        match = ("remote", CloudRef({"id": sid}))
                if not match:
                    why = ("cloud API unavailable (" + str(cloud_get.last_error or "no CLI login token")
                           + ") and the session is not in Claude Desktop's local cache")
                    print(f"error: remote session '{sid}': {why}. Log in with the claude CLI "
                          "(the token is reused) for complete cloud history.", file=sys.stderr)
                    sys.exit(1)
            if not match:
                print(f"error: no session matching '{sid}' "
                      f"(agent={args.agent}, scope={'all projects' if args.all_projects else 'current project'})",
                      file=sys.stderr)
                sys.exit(1)
            targets.append(match)

    outputs = []
    for agent, path in targets:
        parsed = parse_any(agent, path, all_text=not args.final_only)
        if agent == "codex":
            titles = codex_index_titles()
            if parsed["session_id"] in titles:
                parsed["title"] = titles[parsed["session_id"]]
        if args.last:
            user_idx = [i for i, t in enumerate(parsed["turns"]) if t["role"] == "user"]
            if len(user_idx) > args.last:
                cut = user_idx[-args.last]
                parsed["omitted_users"] = len(user_idx) - args.last
                parsed["turns"] = parsed["turns"][cut:]
        outputs.append(parsed)

    if args.json:
        result = json.dumps(outputs if len(outputs) > 1 else outputs[0],
                            indent=2, ensure_ascii=False, default=str)
    else:
        result = "\n\n".join(render_markdown(p, args.max_chars) for p in outputs)

    if args.out:
        Path(args.out).write_text(result, encoding="utf-8")
        total_turns = sum(len(p["turns"]) for p in outputs)
        print(f"Wrote {len(result):,} chars ({total_turns} turns) to {args.out}")
    else:
        print(result)
    print(import_summary(len(result)), file=sys.stderr)


