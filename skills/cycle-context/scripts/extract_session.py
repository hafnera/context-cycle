def munge_path(path):
    """Replicate Claude Code's project-dir naming: non-alphanumerics become '-'."""
    return re.sub(r"[^A-Za-z0-9]", "-", str(Path(path).expanduser().resolve()))


def iter_jsonl(path):
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                yield json.loads(line)
            except json.JSONDecodeError:
                continue


def parse_ts(value):
    if not value:
        return None
    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except ValueError:
        return None


def fmt_ts(dt, with_date=True):
    if dt is None:
        return "?"
    local = dt.astimezone()
    return local.strftime("%Y-%m-%d %H:%M" if with_date else "%H:%M")


def strip_reminders(text):
    return SYSTEM_REMINDER_RE.sub("", text).strip()


def snippet(text, limit=90):
    text = re.sub(r"\s+", " ", text).strip()
    return text if len(text) <= limit else text[: limit - 1] + "…"


