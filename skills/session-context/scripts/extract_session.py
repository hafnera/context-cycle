#!/usr/bin/env python3
"""Extract condensed transcripts from local agent CLI sessions.

Supported agents:
  - Claude Code : ~/.claude/projects/<munged-cwd>/<session-id>.jsonl
  - Codex CLI   : ~/.codex/sessions/YYYY/MM/DD/rollout-*.jsonl

The condensed transcript keeps only real user messages and the FINAL
assistant answer of each turn. Tool calls, tool results, intermediate
status messages, thinking blocks, hook/meta noise and system reminders
are dropped, so a long working session collapses to its essence.

Usage:
  extract_session.py list    [--project PATH | --all-projects] [--agent claude|codex|all]
                             [-n N] [--grep TEXT] [--include-empty] [--json]
  extract_session.py extract SESSION_ID_PREFIX [--project PATH | --all-projects]
                             [--agent claude|codex|all] [--all-text] [--max-chars N]
                             [--json] [-o FILE]
  extract_session.py extract --path FILE [--agent claude|codex] [...]

Stdlib only, no dependencies.
"""

import argparse
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

CLAUDE_PROJECTS_DIR = Path.home() / ".claude" / "projects"
CODEX_SESSIONS_DIR = Path.home() / ".codex" / "sessions"
CODEX_INDEX_FILE = Path.home() / ".codex" / "session_index.jsonl"

# A session file modified this recently is probably the one currently running.
ACTIVE_WINDOW_SECONDS = 180

CLAUDE_USER_NOISE_PREFIXES = (
    "Caveat: The messages below were generated by the user while running local commands",
    "<command-name>",
    "<command-message>",
    "<local-command-stdout>",
    "<local-command-caveat>",
    "<bash-input>",
    "<bash-stdout>",
    "<bash-stderr>",
    "[Request interrupted by user",
    "No response requested.",
)

CODEX_USER_NOISE_PREFIXES = (
    "<environment_context>",
    "<ENVIRONMENT_CONTEXT>",
    "<user_instructions>",
    "<USER_INSTRUCTIONS>",
    "<turn_aborted>",
    "<permissions",
    "# Context from my IDE setup",
    "[Request interrupted",
)

SYSTEM_REMINDER_RE = re.compile(
    r"<(system-reminder|ide_opened_file|ide_opened_files|ide_selection|ide_diagnostics)>"
    r".*?</\1>",
    re.DOTALL,
)

CODEX_NOISE_BLOCK_RE = re.compile(
    r"<(environment_context|ENVIRONMENT_CONTEXT|user_instructions|USER_INSTRUCTIONS|"
    r"recommended_plugins|turn_context)>.*?</\1>",
    re.DOTALL,
)

COMMAND_NAME_RE = re.compile(r"<command-name>(.*?)</command-name>", re.DOTALL)
COMMAND_ARGS_RE = re.compile(r"<command-args>(.*?)</command-args>", re.DOTALL)


def munge_path(path):
    """Replicate Claude Code's project-dir naming: non-alphanumerics become '-'."""
    return re.sub(r"[^A-Za-z0-9]", "-", str(Path(path).expanduser().resolve()))


def iter_jsonl(path):
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                yield json.loads(line)
            except json.JSONDecodeError:
                continue


def parse_ts(value):
    if not value:
        return None
    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except ValueError:
        return None


def fmt_ts(dt, with_date=True):
    if dt is None:
        return "?"
    local = dt.astimezone()
    return local.strftime("%Y-%m-%d %H:%M" if with_date else "%H:%M")


def strip_reminders(text):
    return SYSTEM_REMINDER_RE.sub("", text).strip()


def snippet(text, limit=90):
    text = re.sub(r"\s+", " ", text).strip()
    return text if len(text) <= limit else text[: limit - 1] + "…"


