def claude_session_files(project=None, all_projects=False):
    if not CLAUDE_PROJECTS_DIR.is_dir():
        return []
    if all_projects:
        dirs = [d for d in CLAUDE_PROJECTS_DIR.iterdir() if d.is_dir()]
    else:
        target = CLAUDE_PROJECTS_DIR / munge_path(project or Path.cwd())
        dirs = [target] if target.is_dir() else []
    files = []
    for d in dirs:
        files.extend(f for f in d.glob("*.jsonl") if f.is_file())
    return sorted(files, key=lambda f: f.stat().st_mtime, reverse=True)


def codex_session_files(project=None, all_projects=False):
    if not CODEX_SESSIONS_DIR.is_dir():
        return []
    files = sorted(CODEX_SESSIONS_DIR.rglob("rollout-*.jsonl"),
                   key=lambda f: f.stat().st_mtime, reverse=True)
    if all_projects:
        return files
    wanted = str(Path(project or Path.cwd()).expanduser().resolve())
    matched = []
    for f in files:
        meta = codex_read_meta(f)
        if meta and meta.get("cwd") == wanted:
            matched.append(f)
    return matched


def discover(agent, project, all_projects):
    files = []
    if agent in ("claude", "all"):
        files += [("claude", f) for f in claude_session_files(project, all_projects)]
    if agent in ("codex", "all"):
        files += [("codex", f) for f in codex_session_files(project, all_projects)]
    return sorted(files, key=lambda af: af[1].stat().st_mtime, reverse=True)


