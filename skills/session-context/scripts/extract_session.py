def codex_read_meta(path):
    """Cheaply read session_meta from the first line."""
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            first = f.readline()
        entry = json.loads(first)
    except (OSError, json.JSONDecodeError):
        return None
    if entry.get("type") != "session_meta":
        return None
    payload = entry.get("payload") or {}
    return {"id": payload.get("id"), "cwd": payload.get("cwd"),
            "ts": parse_ts(payload.get("timestamp") or entry.get("timestamp"))}


def codex_index_titles():
    titles = {}
    if CODEX_INDEX_FILE.exists():
        for entry in iter_jsonl(CODEX_INDEX_FILE):
            if entry.get("id") and entry.get("thread_name"):
                titles[entry["id"]] = entry["thread_name"]
    return titles


def parse_codex_session(path, all_text=False):
    turns = []
    pending = []
    meta = {"agent": "codex", "path": str(path), "session_id": None,
            "cwd": None, "title": None, "first_ts": None, "last_ts": None}

    def flush_assistant():
        nonlocal pending
        if not pending:
            return
        text = "\n\n".join(pending) if all_text else pending[-1]
        pending = []
        if text.strip():
            turns.append({"role": "assistant", "text": text.strip(), "ts": None})

    for entry in iter_jsonl(path):
        ts = parse_ts(entry.get("timestamp"))
        if ts:
            meta["first_ts"] = meta["first_ts"] or ts
            meta["last_ts"] = ts
        etype = entry.get("type")
        payload = entry.get("payload") or {}
        if etype == "session_meta":
            meta["session_id"] = payload.get("id")
            meta["cwd"] = payload.get("cwd")
            continue
        if etype != "response_item" or payload.get("type") != "message":
            continue
        role = payload.get("role")
        parts, has_image = [], False
        for item in payload.get("content") or []:
            if not isinstance(item, dict):
                continue
            if item.get("type") in ("input_text", "output_text", "text"):
                if item.get("text"):
                    parts.append(item["text"])
            elif item.get("type") == "input_image":
                has_image = True
        text = "\n".join(parts).strip()
        if role == "user":
            text = CODEX_NOISE_BLOCK_RE.sub("", text).strip()
            if not text and not has_image:
                continue
            if text and is_noise(text, CODEX_USER_NOISE_PREFIXES):
                continue
            if has_image:
                text = (text + "\n" if text else "") + "*[image attached]*"
            flush_assistant()
            turns.append({"role": "user", "text": text, "ts": ts})
        elif role == "assistant" and text:
            pending.append(text)
    flush_assistant()
    meta["session_id"] = meta["session_id"] or Path(path).stem
    meta["turns"] = turns
    meta["user_messages"] = sum(1 for t in turns if t["role"] == "user")
    if not meta["title"]:
        first = next((t for t in turns if t["role"] == "user"), None)
        meta["title"] = snippet(first["text"]) if first else "(empty session)"
    return meta


